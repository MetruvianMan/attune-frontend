export interface EmojiPickerOptions {
  onSelect: (emoji: string) => void;
  selectedEmoji?: string;
}

/**
 * Creates and returns an emoji picker element with categories and scrollable grid.
 * Calls onSelect when an emoji is picked.
 */
export function createEmojiPicker(options: EmojiPickerOptions): HTMLElement {
  const { onSelect, selectedEmoji } = options;

  // Get recently used emojis from localStorage
  const getRecentEmojis = (): string[] => {
    try {
      const stored = localStorage.getItem('attune-recent-emojis');
      return stored ? JSON.parse(stored) : [];
    } catch {
      return [];
    }
  };

  const addRecentEmoji = (emoji: string): void => {
    try {
      let recent = getRecentEmojis();
      recent = recent.filter(e => e !== emoji); // Remove if exists
      recent.unshift(emoji); // Add to front
      recent = recent.slice(0, 24); // Keep only last 24
      localStorage.setItem('attune-recent-emojis', JSON.stringify(recent));
    } catch {
      // Ignore localStorage errors
    }
  };

  // Add recent emojis category if available
  const recentEmojis = getRecentEmojis();
  const categories = recentEmojis.length > 0
    ? [{ name: 'Recently Used', icon: '🕐', emojis: recentEmojis }, ...EMOJI_CATEGORIES]
    : EMOJI_CATEGORIES;

  let currentCategory = 0;
  let currentSelected = selectedEmoji;

  const wrapper = document.createElement('div');
  wrapper.style.cssText = 'margin-bottom:8px;';

  // ── Category Tabs ──
  const tabsRow = document.createElement('div');
  tabsRow.style.cssText = 'display:flex;gap:4px;overflow-x:auto;padding-bottom:6px;scrollbar-width:none;-ms-overflow-style:none;';
  tabsRow.style.setProperty('-webkit-overflow-scrolling', 'touch');

  const tabButtons: HTMLButtonElement[] = [];

  for (let i = 0; i < categories.length; i++) {
    const cat = categories[i];
    const tab = document.createElement('button');
    tab.textContent = cat.icon;
    tab.title = cat.name;
    tab.style.cssText = buildTabStyle(i === currentCategory);
    tab.addEventListener('click', () => {
      currentCategory = i;
      updateTabs();
      renderGrid();
      scrollGridToTop();
    });
    tabButtons.push(tab);
    tabsRow.appendChild(tab);
  }

  wrapper.appendChild(tabsRow);

  // ── Emoji Grid ──
  const gridContainer = document.createElement('div');
  gridContainer.style.cssText = 'max-height:140px;overflow-y:auto;scrollbar-width:none;-ms-overflow-style:none;border:1px solid var(--border);border-radius:10px;padding:6px;';

  wrapper.appendChild(gridContainer);

  // ── Helpers ──

  function buildTabStyle(active: boolean): string {
    const base = 'height:24px;min-width:28px;padding:0 6px;border-radius:12px;border:none;font-size:0.8rem;cursor:pointer;flex-shrink:0;transition:all 0.12s;';
    if (active) {
      return base + 'background:var(--accent);filter:none;';
    }
    return base + 'background:rgba(0,0,0,0.05);';
  }

  function updateTabs(): void {
    for (let i = 0; i < tabButtons.length; i++) {
      tabButtons[i].style.cssText = buildTabStyle(i === currentCategory);
    }
  }

  function scrollGridToTop(): void {
    gridContainer.scrollTop = 0;
  }

  function renderGrid(): void {
    gridContainer.innerHTML = '';

    const grid = document.createElement('div');
    grid.style.cssText = 'display:flex;flex-wrap:wrap;gap:3px;';

    const emojis = categories[currentCategory].emojis;

    for (const emoji of emojis) {
      const btn = document.createElement('button');
      btn.textContent = emoji;
      btn.style.cssText = buildEmojiButtonStyle(emoji === currentSelected);
      btn.addEventListener('click', () => {
        if (currentSelected === emoji) {
          // Deselect
          currentSelected = undefined;
        } else {
          currentSelected = emoji;
        }
        addRecentEmoji(emoji); // Track usage
        onSelect(currentSelected ?? '');
        renderGrid();
      });
      grid.appendChild(btn);
    }

    gridContainer.appendChild(grid);
  }

  function buildEmojiButtonStyle(selected: boolean): string {
    const base = 'width:34px;height:34px;border-radius:8px;font-size:1.1rem;cursor:pointer;display:flex;align-items:center;justify-content:center;transition:all 0.1s;padding:0;';
    if (selected) {
      return base + 'border:2px solid var(--accent);background:rgba(74,144,226,0.12);';
    }
    return base + 'border:2px solid transparent;background:transparent;';
  }

  // Initial render
  renderGrid();

  return wrapper;
}
